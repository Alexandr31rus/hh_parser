"""CLI-скрипт для пересоздания схемы БД.

Запускается как модуль из корня проекта::

    python -m src.app.create_db

Спрашивает подтверждение, затем удаляет все таблицы, описанные в
моделях, и создаёт их заново. Используется при разработке, когда
нужно сбросить локальную базу после изменения моделей.

Warning:
    Уничтожает все данные.
"""

from . import models  # noqa: F401 — регистрирует модели в Base.metadata
from .database import create_db

if __name__ == "__main__":
    # Пересоздаём БД только после явного подтверждения пользователя:
    # drop_all уничтожает данные, случайный запуск недопустим.
    if input("Создать новую БД? Y/N:") == "Y":
        try:
            create_db()
            print("БД успешно обновлена")
        except Exception as ex:
            print(f"Произошла ошибка при создании БД. {ex}")
